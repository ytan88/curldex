"""Documentation, generated from an app's api.yaml (with each API's example) and its verified examples
(verify.py):

- index():      the APIs, one row each (apis(), `curldex <app>`)
- help_text():  one API's params and example command (help(), `curldex <app> <api>`)
- reference():  the full reference, API.md (docs(), `curldex docs <app>`)

One format for people, Claude and developers: Markdown that also reads well in a terminal.
"""

from __future__ import annotations

import json
import textwrap
from typing import TYPE_CHECKING

from .config import ConfigError, UsageError, placeholders, short
from .curl import readable
from .endpoint import Access, Endpoint, Param
from .verify import Verified, example_curl, load_verified

if TYPE_CHECKING:
    from .webapp import WebApp


def index(app: WebApp) -> str:
    """The APIs, one row each, and whether the app is ready to use."""
    head = f"{app.name}: {app.description}\nauth: {app.auth.KIND} ({app.status()})"
    if not app.endpoints:
        return head
    return (f"{head}\n\n{api_table(app)}\n\n"
            f'One API\'s params and example: app.help("<api>"), or `curldex {app.name} <api>`. '
            'Its curl command in Python: app.curl("<api>", param=value, ...).')


def help_text(app: WebApp, api: str | None = None) -> str:
    """One API's help, or the index and every API's help."""
    verified = load_verified(app)
    if api is not None:
        endpoint = app.endpoint(api)
        return api_help(app, endpoint, verified.get(endpoint.name))
    return "\n\n".join([index(app), *(api_help(app, e, verified.get(e.name)) for e in app.endpoints.values())])


def api_help(app: WebApp, endpoint: Endpoint, verified: Verified | None = None, shared: bool = False) -> str:
    """An API's method and path, access level, params, and an example curl command.
    `shared` (for API.md) shows <key> where a value would come from the user's credentials."""
    e = endpoint
    body = {"json": "", "form": "; form body", "multipart": "; multipart body (files as @path)",
            "raw": f"; raw body ({e.content_type or 'application/octet-stream'})"}[e.format]
    lines = [f"### {e.name}", "", f"`{e.method} {e.path}`: **{e.access.value}** ({e.access.meaning}){body}"]
    if e.description:
        lines += ["", e.description]
    if e.params:
        rows = [[p.name, p.location, p.type, _need(p), _about(p)] for p in e.params.values()]
        lines += ["", table(["Param", "In", "Type", "Required / default", "Description"], rows)]
    lines += ["", f"Example, {verified.note() if verified else 'not verified yet'}:", "",
              "```bash", _command(app, e, shared), "```"]
    if verified and verified.ok and verified.shape != "null":  # "null": no body (a 204, say)
        lines += ["", f"Response: `{verified.shape}`"]
    return "\n".join(lines)


def reference(app: WebApp) -> str:
    """API.md: how to use the app, its authentication, and every API with its example."""
    verified = load_verified(app)
    keyed = bool(app.auth.plain())  # the service takes credentials
    setup = f'import curldex\napp = curldex.load_app("{app.name}")'
    if keyed:
        setup += '\napp.status()                # "ready"? If not, it says what to do first'
    if app.auth.LOGIN:
        setup += "\napp.login()                 # once: log in (for OAuth, allow access in the browser)"
    # the first read API that needs no value, so that the snippet runs as it is
    first = next((n for n, e in app.endpoints.items() if e.access is Access.READ
                  and not any(p.mandatory for p in e.params.values())), next(iter(app.endpoints), "<api>"))
    ipython = textwrap.indent(f'{setup}\napp.apis()\ncmd = app.curl("{first}")\n!{{cmd}} | jq .', "  ")
    found = f"{app.IMPORTER.FORMAT}: {app.source['url']}" if app.source.get("url") else "config/api.yaml"
    passed = sum(verified[name].ok for name in app.endpoints if name in verified)
    parts = [
        f"<!-- Generated by `curldex docs {app.name}` from config/api.yaml and config/verified.yaml. "
        "Don't edit it: change those files and run the command again. -->",
        f"# {app.name}\n\n{app.description}",
        f"- **Base URL:** {app.base_url}\n- **Described in:** {found}\n"
        f"- **APIs:** {len(app.endpoints)}, with {passed} examples verified against the service",
        "## How to use it",
        "Each API below has an example curl command. It runs in a shell, or from Claude's Bash tool, once "
        + ("the credentials are set up (see Authentication) and " if keyed else "")
        + "each value in angle brackets, such as `<id>`, is filled in.",
        f"- **Shell:** `curldex {app.name}` lists the APIs; `curldex {app.name} <api>` shows one, with its example.\n"
        + ("- **IPython:** check the app is ready (logging in if needed), build a command, and run it with "
           if keyed else "- **IPython:** build a command, and run it with ")
        + f"`!`:\n\n  ```python\n{ipython}\n  ```\n\n"
        "- **Access levels:** *read* APIs only read data; *write* APIs create or change it; *destructive* "
        "APIs delete or replace it, so run those only when that's intended, after checking the target.\n"
        "- **Debugging:** add `-D -` to see the response headers, or `-o /dev/null -w '%{http_code}\\n'` for "
        "just the status (in IPython, double the braces)."
        + (" Don't use `-v` or `--trace`: they print the Authorization header, token included.\n"
           "- **If curl says** `option -K: error encountered when reading a file`, curldex couldn't provide the "
           "credentials, and the line before it says why: usually that you need to log in (see Authentication)."
           if keyed else ""),
        "## Authentication",
        app.auth.describe().strip() + _used_values(app),
        "## APIs",
        api_table(app),
        *(api_help(app, e, verified.get(e.name), shared=True) for e in app.endpoints.values()),
    ]
    return "\n\n".join(parts) + "\n"


def _command(app: WebApp, endpoint: Endpoint, shared: bool) -> str:
    """The example curl command; if a value from credentials.yaml isn't set yet, the shared form
    (with <key> for it) and what to set."""
    try:
        return readable(example_curl(app, endpoint, shared=shared).command("curldex" if shared else None))
    except ConfigError as error:
        if shared:
            raise
        return f"# {error}\n" + _command(app, endpoint, shared=True)
    except UsageError as error:
        return f"# the example doesn't fit the API: {error}"


def api_table(app: WebApp) -> str:
    rows = [[e.name, e.access.value, e.method, e.path, short(e.description, 80)] for e in app.endpoints.values()]
    return table(["API", "Access", "Method", "Path", "Description"], rows)


def table(header: list[str], rows: list[list[str]]) -> str:
    """A Markdown table, padded so it reads as plain text too."""
    cells = [[cell.replace("|", "\\|") for cell in row] for row in [header, *rows]]
    widths = [max(len(row[i]) for row in cells) for i in range(len(header))]
    lines = ["| " + " | ".join(cell.ljust(w) for cell, w in zip(row, widths, strict=True)) + " |" for row in cells]
    lines.insert(1, "|" + "|".join("-" * (w + 2) for w in widths) + "|")
    return "\n".join(lines)


def _used_values(app: WebApp) -> str:
    keys = app.used_credentials()
    if not keys:
        return ""
    listed = ", ".join(f"`{key}`" for key in keys)
    return (f"\n\n**Values the APIs take from credentials.yaml:** {listed}. The examples below show them as "
            f"{', '.join(f'`<{key}>`' for key in keys)}; `curldex {app.name} <api>` and `app.curl(...)` fill them in.")


def _need(p: Param) -> str:
    if p.mandatory:
        return "required"
    if p.default is None:
        return ""
    if placeholders(p.default):
        return f"{p.default} (credentials.yaml)"
    return f"default {p.default if isinstance(p.default, str) else json.dumps(p.default)}"


def _about(p: Param) -> str:
    about = p.description if not p.enum or not p.description or p.description[-1] in ".!?" else p.description + "."
    choices = f" One of: {', '.join(map(str, p.enum))}." if p.enum else ""
    return short(about + choices, 160).strip()
