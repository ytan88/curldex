def test_curl_options_are_only_the_safe_ones(make_app):
    """Others could send the credentials to another host, or write files."""
    api = "base_url: {url}\nauth: {auth}\ncurl_options: OPTIONS\ncommands:\n  me: {{path: /me}}\n"
    app = make_app(api=api.replace("OPTIONS", "[--compressed, --cacert, /etc/ca.pem, --max-time, 30]"))
    assert app.curl("me").args()[4:9] == ["--compressed", "--cacert", "/etc/ca.pem", "--max-time", "30"]
    for options, message in [("[-L]", "can't hold -L"), ("[--location-trusted]", "can't hold --location-trusted"),
                             ("[-o, /tmp/x]", "can't hold -o"), ("[-Lo, /tmp/x]", "can't hold -Lo"),
                             ("[--url, https://elsewhere.test]", "can't hold --url"), ("[-K, /tmp/c]", "can't hold -K"),
                             ("[--max-time]", "--max-time needs a value")]:
        with pytest.raises(ConfigError, match=re.escape(message)):
            make_app(name=f"app{abs(hash(options))}", api=api.replace("OPTIONS", options))


