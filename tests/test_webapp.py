def test_apis_and_help(make_app, capsys):
    app = make_app()
    app.apis()
    out = capsys.readouterr().out
    assert "testapp: A test service\nauth: none (ready)" in out
    assert "| delete-event | destructive | DELETE | /events/{id}" in out
    app.help("list-events")
    out = capsys.readouterr().out
    assert re.search(r"\| limit +\| query +\| integer +\| default 10 ", out)
    assert "?limit=10&upcoming=true&owner=u1" in out  # the example, with values from credentials.yaml
    with pytest.raises(UsageError, match="no API 'nope'"):
        app.help("nope")


