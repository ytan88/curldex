BODIES = """\
base_url: {url}
auth: {auth}
commands:
  form:
    method: POST
    path: /form
    format: form
    params: {{name: {{}}, meta: {{type: object}}, tags: {{type: array}}, on: {{type: boolean}}}}
  upload:
    method: POST
    path: /upload
    format: multipart
    params: {{title: {{}}, file: {{type: file}}}}
  raw:
    method: PUT
    path: /raw
    format: raw
    content_type: text/csv
    params: {{data: {{in: json, type: file}}}}
"""


def test_form_multipart_and_raw_bodies(make_app, fake, tmp_path):
    from urllib.parse import parse_qs
    app = make_app(api=BODIES)
    sent = app.run("form", name="a b&c", meta={"k": "v"}, tags=["x", "y"], on=True)
    assert sent["content_type"] == "application/x-www-form-urlencoded"
    assert parse_qs(sent["body"]) == {"name": ["a b&c"], "meta[k]": ["v"], "tags[0]": ["x"], "tags[1]": ["y"],
                                      "on": ["true"]}
    assert "--data-urlencode 'name=a b&c'" in str(app.curl("form", name="a b&c"))
    assert str(app.curl("form")).startswith("curl -q -sS -g --data ''")  # a POST always has a body
    (tmp_path / "hello.txt").write_text("hi there")
    sent = app.run("upload", title="T", file=str(tmp_path / "hello.txt"))
    assert sent["content_type"].startswith("multipart/form-data")
    assert 'name="title"' in sent["body"] and 'filename="hello.txt"' in sent["body"] and "hi there" in sent["body"]
    upload = str(app.curl("upload", file=str(tmp_path / "hello.txt")))
    assert f'-F \'file=@"{tmp_path}/hello.txt"\'' in upload  # the path is double-quoted inside the -F value
    (tmp_path / "rows.csv").write_text("a,b\n1,2\n")
    sent = app.run("raw", data=str(tmp_path / "rows.csv"), yes=True)
    assert sent["method"] == "PUT" and sent["content_type"] == "text/csv" and sent["body"] == "a,b\n1,2\n"
    assert "multipart body" in app.docs() and "raw body (text/csv)" in app.docs()


def test_base_url_and_headers_take_values_from_credentials(make_app, fake):
    app = make_app(api="base_url: '{url}/t/${{tenant}}'\nauth: {auth}\ncurl_options: [--compressed]\n"
                       "headers: {{X-Tenant: '${{tenant}}', X-Version: '2'}}\ncommands:\n  me: {{path: /me}}\n",
                   credentials="tenant: acme\n")
    fake.documents["/t/acme/me"] = {"ok": True}
    assert app.run("me") == {"ok": True}
    assert fake.last["headers"]["X-Tenant"] == "acme" and fake.last["headers"]["X-Version"] == "2"
    assert str(app.curl("me")).startswith("curl -q -sS -g --compressed -H 'X-Tenant: acme'")
    assert example_curl(app, app.endpoint("me"), shared=True).url.endswith("/t/<tenant>/me")
    assert app.used_credentials() == ["tenant"]
    app.credentials.path.write_text("")
    with pytest.raises(ConfigError, match=r"base_url: \$\{tenant\} is not set"):
        app.curl("me")


